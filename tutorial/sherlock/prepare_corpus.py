#!/usr/bin/env python3
"""Turn a plain-text corpus into the two files the rustlab tutorial reads.

rustlab (0.3.7) has no text-file reader and no character<->code conversion,
so this one-off step runs outside rustlab:

    python3 prepare_corpus.py data/adventures.txt [more.txt ...]

writes

    data/ids.csv      one 1-based character id per line (rustlab `load`)
    data/vocab.rlab   `vocab_chars = {...};` a string array indexed by id,
                      plus `vocab_size`, for `run "data/vocab.rlab"`

Options:
    --lower           lowercase the text (smaller vocabulary, faster learning)
    --max-chars N     keep only the first N characters after cleaning
    --out DIR         output directory (default: data/ next to the inputs)

Project Gutenberg headers/footers are stripped automatically when the
"*** START OF" / "*** END OF" markers are present.  Standard library only.
"""
import argparse
import math
import os
import re
import sys
from collections import Counter


def strip_gutenberg(text: str) -> str:
    start = re.search(r"\*\*\* ?START OF (THE|THIS) PROJECT GUTENBERG EBOOK[^\n]*\*\*\*", text)
    end = re.search(r"\*\*\* ?END OF (THE|THIS) PROJECT GUTENBERG EBOOK[^\n]*\*\*\*", text)
    if start:
        text = text[start.end():]
    if end:
        text = text[: end.start() - (start.end() if start else 0)] if start else text[: end.start()]
    return text


def clean(text: str) -> str:
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    # Typographic quotes/dashes -> ASCII so the vocabulary stays small.
    for a, b in {"‘": "'", "’": "'", "“": '"', "”": '"',
                 "—": "--", "–": "-", "…": "...", " ": " "}.items():
        text = text.replace(a, b)
    # Collapse runs of blank lines to at most one blank line.
    text = re.sub(r"\n{3,}", "\n\n", text)
    # Drop any remaining non-ASCII characters.
    text = "".join(ch for ch in text if ord(ch) < 128)
    return text.strip() + "\n"


def rlab_string(ch: str) -> str:
    """A rustlab expression producing the one-character string `ch`.

    rustlab string literals have no escape sequences (a backslash is a
    literal backslash and a double quote always terminates the literal),
    so quote, backslash, newline and tab are produced with sprintf("%c").
    """
    if ch in ('"', "\\", "\n", "\t") or ord(ch) < 32:
        return 'sprintf("%%c", %d)' % ord(ch)
    return '"' + ch + '"'


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("inputs", nargs="+", help="plain-text files (concatenated in order)")
    ap.add_argument("--lower", action="store_true")
    ap.add_argument("--max-chars", type=int, default=0)
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    out_dir = args.out or os.path.join(os.path.dirname(os.path.abspath(args.inputs[0])))
    os.makedirs(out_dir, exist_ok=True)

    text = ""
    for path in args.inputs:
        with open(path, encoding="utf-8", errors="replace") as f:
            text += clean(strip_gutenberg(f.read())) + "\n"
    if args.lower:
        text = text.lower()
    if args.max_chars > 0:
        text = text[: args.max_chars]

    chars = sorted(set(text))
    index = {ch: i + 1 for i, ch in enumerate(chars)}  # 1-based ids for rustlab
    ids = [index[ch] for ch in text]

    ids_path = os.path.join(out_dir, "ids.csv")
    with open(ids_path, "w") as f:
        f.write("\n".join(str(i) for i in ids) + "\n")

    vocab_path = os.path.join(out_dir, "vocab.rlab")
    with open(vocab_path, "w") as f:
        f.write("# Generated by prepare_corpus.py -- do not edit.\n")
        f.write("# vocab_chars(id) is the character for 1-based token id; vocab_size = %d.\n" % len(chars))
        f.write("vocab_chars = {" + ", ".join(rlab_string(c) for c in chars) + "};\n")
        f.write("vocab_size = %d;\n" % len(chars))
        f.write("corpus_chars = %d;\n" % len(ids))

    # Order-0 entropy, for the README and as the first floor of the lessons.
    counts = Counter(ids)
    n = len(ids)
    h0 = -sum(c / n * math.log2(c / n) for c in counts.values())
    print(f"characters      : {n:,}")
    print(f"vocabulary size : {len(chars)}")
    print(f"order-0 entropy : {h0:.3f} bits/char  (log2 V = {math.log2(len(chars)):.3f})")
    print(f"wrote {ids_path} and {vocab_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
